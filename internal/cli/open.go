// editorCommand is the VS Code launcher (SCOPE.md §5.4).
const editorCommand = "code"

// editorHint is printed when the launcher is not on PATH.
const editorHint = "install the VS Code 'code' command"

// cmdShimPath is the only path shape handed to the Windows `code.cmd` shim.
// COWFlow builds workspace paths from [workspace].root and a validated slug,
// so a path outside this allow-list was not generated by COWFlow. A batch
// file runs through cmd.exe, which would interpret any other character
// (SCOPE.md §7: no shell strings).
var cmdShimPath = regexp.MustCompile(`^[A-Za-z]:\\[A-Za-z0-9_.\\-]+$`)

// EditorSeams are the process-level calls of `open`. The zero value is
// production; tests inject fakes so no editor is ever started.
type EditorSeams struct {
	// GOOS names the operating system; empty means runtime.GOOS.
	GOOS string
	// LookPath resolves the launcher; nil means exec.LookPath.
	LookPath func(file string) (string, error)
	// Start launches argv[0] with argv[1:] (an argument array, never a shell
	// string) without waiting for it; nil starts and detaches a process.
	Start func(ctx context.Context, argv []string) error
}

func (e EditorSeams) goos() string {
	if e.GOOS != "" {
		return e.GOOS
	}
	return runtime.GOOS
}

func (e EditorSeams) lookPath(file string) (string, error) {
	if e.LookPath != nil {
		return e.LookPath(file)
	}
	return exec.LookPath(file)
}

func (e EditorSeams) start(ctx context.Context, argv []string) error {
	if e.Start != nil {
		return e.Start(ctx, argv)
	}
	return startDetached(ctx, argv)
}

// startDetached starts argv and releases the process: the CLI never waits
// for the editor. The child gets no standard streams.
func startDetached(ctx context.Context, argv []string) error {
	if len(argv) == 0 {
		return errors.New("empty command")
	}
	cmd := exec.CommandContext(ctx, argv[0], argv[1:]...) //nolint:gosec // argv array, no shell; the program is LookPath's result
	if err := cmd.Start(); err != nil {
		return err
	}
	return cmd.Process.Release()
}

// TaskLookup finds a task by slug. *store.Store implements it.
type TaskLookup interface {
	GetTaskBySlug(ctx context.Context, projectID, slug string) (domain.Task, error)
}

// WorkspaceLister lists workspaces. *workspace.Manager implements it.
type WorkspaceLister interface {
	List(ctx context.Context, f workspace.ListFilter) ([]workspace.Workspace, error)
}

// openedBackend is a task backend opened for one command, with the project
// of the current repository.
type openedBackend struct {
	cfg     *config.Config
	be      TaskBackend
	project domain.Project
	close   func()
}

// openProject loads the config, opens the daemonless backend and finds the
// project of the repository the config belongs to. The caller must call
// close.
func openProject(ctx context.Context, deps Deps, command string) (*openedBackend, error) {
	cfgPath, err := deps.ConfigPath()
	if err != nil {
		return nil, &ExitError{Code: ExitState, Err: err}
	}
	cfg, err := config.Load(cfgPath)
	if err != nil {
		return nil, configErr(err)
	}
	if deps.OpenTasks == nil {
		return nil, &ExitError{Code: exitUnsupported, Err: fmt.Errorf("%s is not available in this build", command)}
	}
	be, err := deps.OpenTasks(ctx, cfg, cfgPath)
	if err != nil {
		return nil, &ExitError{Code: ExitState, Err: fmt.Errorf("open store: %w", err)}
	}
	o := &openedBackend{cfg: cfg, be: be, close: func() {
		if be.Close != nil {
			_ = be.Close() // a close failure cannot change the outcome
		}
	}}
	// The config sits at <repo>/.cowflow/config.toml (SPEC-GAPS U-API-1).
	repoDir, err := platform.Canonical(filepath.Dir(filepath.Dir(cfgPath)))
	if err != nil {
		o.close()
		return nil, &ExitError{Code: ExitState, Err: err}
	}
	o.project, err = be.Store.ProjectByRoot(ctx, repoDir)
	if errors.Is(err, store.ErrNotFound) {
		o.close()
		return nil, &ExitError{Code: ExitState, Err: fmt.Errorf("project %s is not initialized: run cowflow init", repoDir)}
	}
	if err != nil {
		o.close()
		return nil, &ExitError{Code: ExitState, Err: err}
	}
	return o, nil
}

func newOpenCmd(ios IOStreams, deps Deps, st *runState) *cobra.Command {
	return &cobra.Command{
		Use:   "open <task>",
		Short: "Open a task's workspace",
		Long: "Open the most recent ready workspace of a task in VS Code.\n\n" +
			"With --json it prints {\"path\": \"...\"} and starts nothing. Without the " +
			"'code' command on PATH it prints the path. One workspace is opened per call.",
		Args: cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runOpen(cmd.Context(), ios, deps, st, args[0])
		},
	}
}

type openDoc struct {
	Path string `json:"path"`
}

func runOpen(ctx context.Context, ios IOStreams, deps Deps, st *runState, slug string) error {
	if err := domain.ValidateSlug(slug); err != nil {
		return usageErr(err)
	}
	o, err := openProject(ctx, deps, "open")
	if err != nil {
		return err
	}
	defer o.close()
	if o.be.Tasks == nil || o.be.Lister == nil {
		return &ExitError{Code: exitUnsupported, Err: errors.New("open is not available in this build")}
	}
	task, err := o.be.Tasks.GetTaskBySlug(ctx, o.project.ID, slug)
	if errors.Is(err, store.ErrNotFound) {
		return &ExitError{Code: ExitState, Err: fmt.Errorf("task %q not found", slug)}
	}
	if err != nil {
		return &ExitError{Code: exitUnclassified, Err: err}
	}
	list, err := o.be.Lister.List(ctx, workspace.ListFilter{
		ProjectID: o.project.ID, TaskID: task.ID, States: []domain.WorkspaceState{domain.WorkspaceReady},
	})
	if err != nil {
		return workspaceErr(err)
	}
	ws, ok := latestWorkspace(list)
	if !ok {
		return &ExitError{Code: ExitState, Err: fmt.Errorf("task %q has no ready workspace", slug)}
	}
	if st.json {
		return printResult(ios, true, openDoc{Path: ws.Path}, nil)
	}

	code, err := deps.Editor.lookPath(editorCommand)
	if err != nil {
		_, _ = fmt.Fprintln(ios.Out, ws.Path)
		_, _ = fmt.Fprintf(ios.Err, "hint: %s\n", editorHint)
		return nil
	}
	if deps.Editor.goos() == "windows" && !safeForCmdShim(ws.Path) {
		return &ExitError{Code: ExitPolicy, Err: fmt.Errorf(
			"refusing to launch the editor through cmd.exe for path %q: open it by hand", ws.Path)}
	}
	if err := deps.Editor.start(ctx, []string{code, ws.Path}); err != nil {
		return &ExitError{Code: ExitState, Err: fmt.Errorf("start %s: %w", editorCommand, err)}
	}
	_, err = fmt.Fprintf(ios.Out, "opened %s\n", ws.Path)
	return err
}

// latestWorkspace returns the most recently created workspace.
func latestWorkspace(list []workspace.Workspace) (workspace.Workspace, bool) {
	var best workspace.Workspace
	found := false
	for _, w := range list {
		if !found || w.CreatedAt.After(best.CreatedAt) {
			best, found = w, true
		}
	}
	return best, found
}

// safeForCmdShim reports whether p may be passed to the Windows code.cmd
// batch shim: the generated shape of a workspace path, and no ".." segment.
func safeForCmdShim(p string) bool {
	if !cmdShimPath.MatchString(p) {
		return false
	}
	for seg := range strings.SplitSeq(p, `\`) {
		if seg == ".." {
			return false
		}
	}
	return true
}
