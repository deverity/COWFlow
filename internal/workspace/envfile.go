package workspace

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/deverity/cowflow/internal/config"
)

// EnvFileName is the file written at the root of every workspace.
const EnvFileName = ".env.cowflow"

const envFileHeader = "# generated by cowflow; do not edit\n"

// EnvFileWriter is the production [EnvWriter] (SCOPE.md §6.1, §6.7). It
// writes ports, identity and the shared cache locations. No session token is
// ever written (§6.1).
type EnvFileWriter struct {
	cache config.Cache
	dev   config.DevDrive
	vols  Volumes
	log   *slog.Logger

	// rename is os.Rename; tests replace it to inject a fault between the
	// temporary write and the rename.
	rename func(oldpath, newpath string) error
}

var _ EnvWriter = (*EnvFileWriter)(nil)

// NewEnvFileWriter returns a writer over cfg's [cache] and [devdrive].
// vols may be nil (no Dev Drive warning); log nil means slog.Default().
func NewEnvFileWriter(cfg *config.Config, vols Volumes, log *slog.Logger) *EnvFileWriter {
	if log == nil {
		log = slog.Default()
	}
	w := &EnvFileWriter{vols: vols, log: log, rename: os.Rename}
	if cfg != nil {
		w.cache, w.dev = cfg.Cache, cfg.DevDrive
	}
	return w
}

// Write creates the cache directories and atomically writes
// <w.Path>/.env.cowflow: sorted KEY=VALUE lines, no quoting or export.
func (e *EnvFileWriter) Write(ctx context.Context, w *Workspace) error {
	if w == nil {
		return errors.New("write .env.cowflow: nil workspace")
	}
	if !filepath.IsAbs(w.Path) {
		return fmt.Errorf("write .env.cowflow: workspace path %q is not absolute", w.Path)
	}
	entries, err := cacheEntries(e.cache, w.ID)
	if err != nil {
		return err
	}
	vars := map[string]string{
		"COWFLOW_PROJECT_ID":       w.ProjectID,
		"COWFLOW_TASK_ID":          w.TaskID,
		"COWFLOW_WORKSPACE_ID":     w.ID,
		"COWFLOW_PORT_RANGE_START": strconv.Itoa(w.Ports.Start),
		"COWFLOW_PORT_RANGE_END":   strconv.Itoa(w.Ports.End),
	}
	for _, c := range entries {
		vars[c.variable] = c.dir
	}
	content, err := renderEnv(vars)
	if err != nil {
		return err
	}
	if err := ensureCacheDirs(ctx, entries, w.Path, e.dev, e.vols, e.log); err != nil {
		return err
	}
	final := filepath.Join(w.Path, EnvFileName)
	tmp := final + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o600); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("write %s: %w", tmp, err)
	}
	if err := e.rename(tmp, final); err != nil {
		_ = os.Remove(tmp)
		return fmt.Errorf("rename %s: %w", tmp, err)
	}
	return nil
}

// renderEnv builds the file content: the header, then the variables sorted
// by name. A value with a newline, carriage return or NUL is an error.
func renderEnv(vars map[string]string) (string, error) {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString(envFileHeader)
	for _, k := range keys {
		if err := checkValue(vars[k]); err != nil {
			return "", fmt.Errorf("write .env.cowflow: %s: %w", k, err)
		}
		b.WriteString(k + "=" + vars[k] + "\n")
	}
	return b.String(), nil
}
